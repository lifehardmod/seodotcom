"""Regenerate local subsets: python3 -m pip install 'fonttools[woff]'; python3 scripts/subset-fonts.py.

The original fonts remain as fallbacks for new copy and user-entered text.
Generated files are committed; Python is not required for a deployment.
"""
from pathlib import Path
from html.parser import HTMLParser
import sys
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
text = "".join(p.read_text() for p in sorted((ROOT / "src").rglob("*")) if p.suffix in {".tsx", ".ts"})
# Include HTML-entity punctuation (e.g. &ldquo;) as well as literal source text.
codepoints = set(map(ord, text)) | set(range(32, 256)) | set(range(0x2000, 0x2070))
fonts = [
    ("PretendardVariable.woff2", "PretendardPortfolio.woff2"),
    ("DNFBitBitv2.ttf", "DNFBitBitPortfolio.woff2"),
    ("PartialSansKR-Regular.otf", "PartialSansPortfolio.woff2"),
    ("Pixel-Regular.ttf", "PixelPortfolio.woff2"),
    ("DungGeunMo.woff2", "DungGeunMoPortfolio.woff2"),
]
output = ROOT / "src/assets/fonts"
output.mkdir(parents=True, exist_ok=True)
families = ["Pretendard", "DNFBitBit", "PartialSansKR", "Pixel-Regular", "DungGeunMo"]
fallbacks = ["/* Generated by scripts/subset-fonts.py. */"]
for source, target in ([] if "--routes-only" in sys.argv else fonts):
    font = TTFont(ROOT / "public/fonts" / source, recalcTimestamp=False)
    original_codepoints = set(font.getBestCmap())
    options = subset.Options()
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(output / target)
    remaining = sorted(original_codepoints - set(font.getBestCmap()))
    ranges = []
    for cp in remaining:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    unicode_range = ",".join(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}" for start, end in ranges)
    family = families[len(fallbacks) - 1]
    weight = "45 920" if family == "Pretendard" else "400"
    fallbacks.append(f'@font-face {{\n  font-family: "{family} Extended";\n  src: url("/fonts/{source}");\n  font-weight: {weight};\n  font-display: optional;\n  unicode-range: {unicode_range};\n}}')
    print(f"{target}: {(output / target).stat().st_size:,} bytes")
if len(fallbacks) > 1:
    (ROOT / "src/styles/font-fallbacks.css").write_text("\n\n".join(fallbacks[:2]) + "\n")
    (ROOT / "src/styles/demo-font-fallbacks.css").write_text("\n\n".join([fallbacks[0], *fallbacks[2:]]) + "\n")

# Each statically rendered route only needs its own text, not every project demo.
# Run `npm run build` once before regenerating, then rebuild to use these files.
class VisibleText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.hidden = 0
        self.parts = []
        self.body = False
        self.main = False
        self.common = []

    def handle_starttag(self, tag, attrs):
        if tag == "body":
            self.body = True
        if tag == "main":
            self.main = True
        if tag in {"script", "style"}:
            self.hidden += 1

    def handle_endtag(self, tag):
        if tag == "body":
            self.body = False
        if tag == "main":
            self.main = False
        if tag in {"script", "style"}:
            self.hidden -= 1

    def handle_data(self, data):
        if not self.hidden:
            self.parts.append(data)
            if self.body and not self.main:
                self.common.append(data)


pages_dir = ROOT / "src/lib/fonts"
pages_dir.mkdir(exist_ok=True)
html_dir = ROOT / ".next/server/app"
html_files = sorted(p for p in html_dir.rglob("*.html") if not p.stem.startswith("_"))
if not html_files:
    raise SystemExit("Build the site before generating route fonts: npm run build")

route_texts = {}
common_text = []
for html in html_files:
    parser = VisibleText()
    parser.feed(html.read_text())
    route = html.relative_to(html_dir).with_suffix("").as_posix()
    name = "home" if route == "index" else route.replace("/", "-")
    route_texts[name] = "".join(parser.parts)
    common_text.extend(parser.common)

route_texts["common"] = "".join(common_text)
for name, rendered_text in route_texts.items():
    characters = set(map(ord, rendered_text)) | {32, 160}
    font = TTFont(output / "PretendardPortfolio.woff2", recalcTimestamp=False)
    site_codepoints = set(font.getBestCmap())
    route_options = subset.Options()
    route_options.flavor = "woff2"
    subsetter = subset.Subsetter(options=route_options)
    subsetter.populate(unicodes=characters)
    subsetter.subset(font)
    font.flavor = "woff2"
    filename = f"Pretendard-{name}.woff2"
    font.save(output / filename)
    extra = sorted(site_codepoints - set(font.getBestCmap()))
    css = (
        '/* Generated fallback for interactive text absent from initial HTML. */\n'
        '@font-face {\n'
        f'  font-family: "Pretendard {name} Supplemental";\n'
        '  src: url("../../assets/fonts/PretendardPortfolio.woff2") format("woff2");\n'
        '  font-weight: 45 920;\n'
        '  font-display: optional;\n'
        '  unicode-range: ' + ','.join(f'U+{cp:X}' for cp in extra) + ';\n}\n'
    )
    (pages_dir / f"{name}.css").write_text(css)
    (pages_dir / f"{name}.ts").write_text(
        '// Generated by scripts/subset-fonts.py from prerendered page text.\n'
        'import localFont from "next/font/local";\n\n'
        f'import "./{name}.css";\n\n'
        'const font = localFont({\n'
        f'  src: "../../assets/fonts/{filename}",\n'
        '  weight: "45 920",\n'
        '  display: "optional",\n'
        '  variable: "--font-portfolio",\n'
        f'  fallback: ["Pretendard {name} Supplemental", "Pretendard Extended", "Arial", "sans-serif"],\n'
        '  adjustFontFallback: false,\n'
        '});\n\nexport default font;\n'
    )
    print(f"{filename}: {(output / filename).stat().st_size:,} bytes")
